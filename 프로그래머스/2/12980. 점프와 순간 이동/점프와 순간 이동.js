function solution(n) {
  // 순간이동(x2)은 공짜, 점프(+1)만 건전지 1 소모
  // 거꾸로 생각: n에서 시작해 짝수면 /2(순간이동 역), 홀수면 -1(점프 역)
  // → 최소 점프 횟수 = n을 이진수로 봤을 때 1의 개수
  let count = 0;
  while (n > 0) {
    if (n % 2 === 1) count++; // 홀수 → 마지막에 +1 점프가 필요했음
    n = Math.floor(n / 2);    // 짝수화 = 순간이동(x2)의 역연산
  }
  return count;
}
// 1. 순간이동은 비용 0 → 점프(+1)를 최소화하는 게 목표
// 2. 목표 지점 n을 거꾸로 되짚으면 짝수는 /2, 홀수는 -1 후 /2
// 3. 홀수인 순간마다 점프 1회 필요 → 결국 n의 이진수 1의 개수
